export function convertRawToAsset(raw: ImportedAssetRaw, officesList: { id: string; name: string; acronym?: string }[]): any {
  // Find office by acronym or name
  let matchedOffice = officesList.find(
    o => (raw.officeAcronym && o.acronym?.toLowerCase() === raw.officeAcronym.toLowerCase()) ||
         (raw.officeName && o.name.toLowerCase().includes(raw.officeName.toLowerCase())) ||
         (raw.officeName && raw.officeName.toLowerCase().includes(o.name.toLowerCase()))
  );

  if (!matchedOffice && raw.officeAcronym) {
    matchedOffice = officesList.find(o => o.name.toLowerCase().includes(raw.officeAcronym!.toLowerCase()));
  }

  const officeId = matchedOffice ? matchedOffice.id : (officesList[0]?.id || '');

  // Condition mapping
  let cond: any = 'Good';
  if (raw.condition) {
    const c = raw.condition.toLowerCase();
    if (c.includes('excel')) cond = 'Excellent';
    else if (c.includes('good')) cond = 'Good';
    else if (c.includes('fair')) cond = 'Fair';
    else if (c.includes('poor')) cond = 'Poor';
    else if (c.includes('defect') || c.includes('unserv')) cond = 'Damaged';
  }

  // Operational status mapping
  let opStatus: any = 'Operational';
  if (raw.inventoryStatus) {
    const s = raw.inventoryStatus.toLowerCase();
    if (s.includes('repair') || s.includes('inspect')) opStatus = 'Under Maintenance';
    else if (s.includes('missing')) opStatus = 'Lost / Missing';
    else if (s.includes('dispose') || s.includes('retired')) opStatus = 'Retired';
    else if (s.includes('storage') || s.includes('spare')) opStatus = 'Operational';
  }
  if (raw.condition && (raw.condition.toLowerCase().includes('defect') || raw.condition.toLowerCase().includes('unserv'))) {
    opStatus = 'Non-Operational';
  }

  return {
    id: raw.assetCode ? `ast_${raw.assetCode.replace(/[^a-zA-Z0-9]/g, '_')}` : `ast_${Math.random().toString(36).substring(2, 9)}`,
    assetCode: raw.assetCode,
    officeId: officeId,
    equipmentType: raw.equipmentType || 'Equipment',
    propertyNumber: raw.propertyNumber !== undefined && raw.propertyNumber !== null && raw.propertyNumber !== '' ? raw.propertyNumber : '',
    inventoryNumber: raw.inventoryNumber || '',
    brand: raw.brand || 'Generic',
    model: raw.model || 'Standard Model',
    serialNumber: raw.serialNumber || 'N/A',
    assignedTo: raw.assignedTo || 'Unassigned',
    condition: cond,
    operationalStatus: opStatus,
    hostname: raw.hostname || '',
    processor: raw.cpu || '',
    memory: raw.ram || '',
    diskStorage: raw.diskStorage || '',
    operatingSystem: raw.operatingSystem || '',
    microsoftOffice: raw.msOffice || '',
    exactLocation: raw.exactLocation || '',
    acquisitionCost: 'N/A',
    dateAcquired: raw.acquisitionDate ? raw.acquisitionDate.split('T')[0] : '2025-01-01',
    dateAudited: new Date().toISOString().split('T')[0],
    auditedBy: 'ICT Audit Team',
    remarks: `Imported asset from municipal inventory. Location: ${raw.exactLocation || 'N/A'}`
  };
}

